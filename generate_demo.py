class DeliveryFactory:
    def __init__(self, rng):
        self.rng = rng
        self.seq = 0

    def make(self, spec, endpoint_key, request_scope, recorded: datetime, payload=None, http_status=200,
             window_start: datetime | None = None, extra_meta=None, error_body_text=None, retry_after_s=None):
        self.seq += 1
        lo, hi = spec["delay_s"]
        delay = float(self.rng.uniform(lo, hi))
        received = recorded + timedelta(seconds=delay)
        mt = {
            "transport_schema": TRANSPORT_SCHEMA,
            "synthetic": True,
            "delivery_id": f"{spec['key']}-{self.seq:07d}",
            "provider_profile_id": PROFILE_IDS[spec["provider"]],
            "endpoint_key": endpoint_key,
            "binding": {"account_id": spec["account_id"], "site_id": spec["site_id"]},
            "request_scope": request_scope,
            "recorded_at_utc": iso_z(recorded),
            "received_at_utc": iso_z(received),
            "http_status": http_status,
            "transport_error": None,
        }
        if retry_after_s is not None:
            mt["retry_after_s"] = retry_after_s
        if error_body_text is not None:
            mt["error_body_text"] = error_body_text
        d = {"mock_transport": mt, "_meta": dict(site=spec["key"], endpoint=endpoint_key, recorded=recorded,
                                                   received=received, seq=self.seq, window_start=window_start,
                                                   **(extra_meta or {}))}
        if payload is not None:
            d["payload"] = payload
        return d


def set_received(d, received: datetime, recorded: datetime | None = None):
    d["_meta"]["received"] = received
    d["mock_transport"]["received_at_utc"] = iso_z(received)
    if recorded is not None:
        d["_meta"]["recorded"] = recorded
        d["mock_transport"]["recorded_at_utc"] = iso_z(recorded)


