def _write_raw(stream, root: Path):
    p = root / stream.path
    p.parent.mkdir(parents=True, exist_ok=True)
    items = sorted(stream.items, key=lambda x: (x[0], x[1]))
    with open(p, "w", encoding="utf-8", newline="\n") as fh:
        for _, _, obj in items:
            fh.write(dumps(obj) + "\n")
    return {"path": stream.path, "dataset": stream.dataset, "family": stream.family, "profile_id": stream.profile_id,
            "endpoint_key": stream.endpoint_key, "asset_ids": [], "format": "ndjson_envelope", "role": stream.role,
            "lines": len(items), "collector_id": "COL-HW-NBI-01", "sha256": sha256_file(p)}


