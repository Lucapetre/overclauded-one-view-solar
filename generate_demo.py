def se_telemetry(spec, sim, i, tl):
    phases = spec["inverter"]["phases"]
    p = sim["inv_ac"][i] * 1000.0
    active = sim["inv_ac"][i] > 0.0
    t = {"date": naive_local(tl.utc(i)), "totalActivePower": r(p, 1),
         "dcVoltage": r((380.0 if phases == 1 else 750.0) + 2.0 * math.sin(i / 37.0), 1) if active else None,
         "powerLimit": 100.0, "totalEnergy": r(sim["lifetime_kwh"][i] * 1000, 1),
         "temperature": r(sim["inv_temp"][i], 1), "inverterMode": "MPPT" if active else "SLEEPING",
         "operationMode": 0}
    for k in range(phases):
        v = sim["volts"][k][i]
        pp = p / phases
        t[f"L{k + 1}Data"] = {"acCurrent": r(pp / v if v > 1 else 0.0, 2), "acVoltage": r(v, 1),
                              "acFrequency": r(sim["freq"][i], 3), "apparentPower": r(pp, 1),
                              "activePower": r(pp, 1), "reactivePower": 0.0, "cosPhi": 1.0}
    if phases == 3:
        t["vL1To2"] = r(math.sqrt(3) * sim["volts"][0][i], 1)
        t["vL2To3"] = r(math.sqrt(3) * sim["volts"][1][i], 1)
        t["vL3To1"] = r(math.sqrt(3) * sim["volts"][2][i], 1)
    return t


def se_powerflow(spec, sim, i, unit="kW"):
    if not spec["meter"]:
        return {}  # documented: sites without power-flow support return an empty object
    f = 1.0 if unit == "kW" else 1000.0
    nd = 2 if unit == "kW" else 0
    load, imp, exp_ = sim["load"][i], sim["imp"][i], sim["exp"][i]
    pv = sim["pv_used"][i] * 0.965 if spec["battery"] else sim["inv_ac"][i]
    g = r(abs(imp - exp_) * f, nd)
    pvv = r(pv * f, nd)
    conns = []
    if pvv > 0:
        conns.append({"from": "PV", "to": "Load"})
    if g > 0 and imp > exp_:
        conns.append({"from": "GRID", "to": "Load"})
    if g > 0 and exp_ > imp:
        conns.append({"from": "LOAD", "to": "Grid"})
    flow = {"updateRefreshRate": 3, "unit": unit, "connections": conns,
            "GRID": {"status": "Active", "currentPower": g},
            "LOAD": {"status": "Active", "currentPower": r(load * f, nd)},
            "PV": {"status": "Active" if pvv > 0 else "Idle", "currentPower": pvv}}
    if spec["battery"]:
        chv, dsv = r(sim["ch"][i] * f, nd), r(sim["dis"][i] * f, nd)
        if chv > 0:
            conns.append({"from": "PV", "to": "Storage"})
        if dsv > 0:
            conns.append({"from": "STORAGE", "to": "Load"})
        flow["STORAGE"] = {"status": "Charging" if chv > 0 else ("Discharging" if dsv > 0 else "Idle"),
                           "currentPower": chv if chv > 0 else dsv,
                           "chargeLevel": int(round(sim["soc"][i])), "critical": False}
    return {"siteCurrentPowerFlow": flow}


