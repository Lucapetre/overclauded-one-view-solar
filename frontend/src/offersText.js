const plural = new Intl.PluralRules(LANGUAGE);

/** Message by id with {name} placeholders filled; unknown ids return the id itself. */
export function t(id, vars = {}) {
  const template = messages[id];
  if (template === undefined) return id;
  return template.replace(/\{(\w+)\}/g, (whole, name) =>
    vars[name] === undefined || vars[name] === null ? whole : String(vars[name]),
  );
}

/** Count-aware message: `${id}.one` or `${id}.other`, with {n} set to the count. */
export function tn(id, n, vars = {}) {
  const form = plural.select(n);
  const key = messages[`${id}.${form}`] !== undefined ? `${id}.${form}` : `${id}.other`;
  return t(key, { n, ...vars });
}
