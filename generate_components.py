def f1_business(tl, wx, sim_f1, rng, derate_at_i):
    n, h = tl.n, tl.local_hour
    pv = sim_f1["inv_ac"].copy()                          # == existing F1 inverter AC output (P_PV / PAC fixtures)
    open_ = (h >= 7.0) & (h < 22.0)
    base = np.where(open_, 0.9, 0.35) * (1 + 0.06 * gd.ar1(rng, n, 0.98))
    washers = np.zeros((3, n))                              # per-phase machine load
    batch = np.zeros(n)
    batch_runs = []
    busy_w = np.zeros((4, n), bool)
    busy_d = np.zeros((2, n), bool)
    for day in range(tl.days):

        weekend = tl.weekday[day] >= 5
        for minute in range(7 * 60, 21 * 60 + 15):
            hh = minute / 60.0
            lam = (0.55 + 1.0 * gd.gauss(hh, 11.0, 1.3) + 0.9 * gd.gauss(hh, 18.5, 1.4)) * (1.3 if weekend else 1.0)
            if rng.random() < lam / 60.0:
                i0 = tl.index_of_local(day, hh)
                free = [k for k in range(4) if not busy_w[k, i0:i0 + 45].any()]
                if not free:
                    continue
                k = free[0]
                busy_w[k, i0:i0 + 45] = True
                ph = k % 2                                  # washers on L1/L2
                washers[ph, i0:i0 + 12] += 2.2
                washers[ph, i0 + 12:i0 + 45] += 0.35
                if rng.random() < 0.7:
                    j0 = i0 + 45 + int(rng.integers(0, 10))
                    freed = [k2 for k2 in range(2) if not busy_d[k2, j0:j0 + 40].any()]
                    if freed:
                        busy_d[freed[0], j0:j0 + 40] = True
                        washers[2, j0:j0 + 40] += 2.6        # dryers on L3
        start_h = 11.0 if tl.dates[day] == date(2026, 7, 17) else 9.0
        a = tl.index_of_local(day, start_h)
        batch[a:a + LAUNDRY_TASK["duration_min"]] = LAUNDRY_TASK["power_kw"]
        batch_runs.append({"date": str(tl.dates[day]), "start_local": f"{int(start_h):02d}:00",
                           "end_local": f"{int(start_h) + 2:02d}:00", "power_kw": 4.0, "energy_kwh": 8.0})
    w = phase_weights(rng, n, [0.4, 0.35, 0.25])
    load_ph = [base * w[k] + washers[k] for k in range(3)]
    load_ph[2] = load_ph[2] + batch
    load = load_ph[0] + load_ph[1] + load_ph[2]
    # ---- AC-coupled battery (battery inverter on L2); E on the storage-energy basis
    B = F1_BATTERY
    cap = B["nominal_v"] * B["capacity_ah"] / 1000.0
    e_min = cap * B["reserve_soc"]
    e = cap * B["soc0"]
    dt = 1 / 60.0
    ch = np.zeros(n)
    dis = np.zeros(n)
    e_arr = np.zeros(n)
    soc = np.zeros(n)
    v_pack = np.zeros(n)
    i_lim_dis = np.where(np.arange(n) >= derate_at_i, B["derated_discharge_a"], B["max_discharge_a"])
    for i in range(n):
        e_arr[i] = e
        soc[i] = 100.0 * e / cap
        v = 49.6 + 4.0 * soc[i] / 100.0
        v_pack[i] = v
        surplus = pv[i] - load[i]
        if surplus > 0.05:
            room = max((cap - e) / (B["eta_c"] * dt), 0.0)
            ch[i] = max(min(surplus, B["inverter_kw"], B["max_charge_a"] * v / 1000.0 / B["pcs_eta"], room), 0.0)
        elif surplus < -0.05:
            avail = max((e - e_min) * B["eta_d"] / dt, 0.0)
            dis[i] = max(min(-surplus, B["inverter_kw"], i_lim_dis[i] * v / 1000.0 * B["pcs_eta"], avail), 0.0)
        e += B["eta_c"] * ch[i] * dt - dis[i] * dt / B["eta_d"]
    p_dc_native = ch * B["pcs_eta"] - dis / B["pcs_eta"]       # + charging (native convention), kW at the DC terminals
    i_dc_native = p_dc_native * 1000.0 / v_pack
    v_term = v_pack + 0.012 * i_dc_native
    tamb = wx["tamb"]
    t_bat = lag1(25.0 + 0.25 * (tamb - 25.0) + 2.0 * np.abs(p_dc_native) / B["inverter_kw"], 30.0)
    net_ph = [load_ph[0] - pv, load_ph[1] + ch - dis, load_ph[2]]
    net = net_ph[0] + net_ph[1] + net_ph[2]
    imp, exp_ = np.maximum(net, 0.0), np.maximum(-net, 0.0)
    balance = pv + imp + dis - (load + exp_ + ch + 0.0)       # residual AC losses declared 0 at this boundary
    assert np.max(np.abs(balance)) < 1e-9, "F1 AC-boundary balance violated"
    e_next = e_arr[1:]
    e_pred = e_arr[:-1] + B["eta_c"] * ch[:-1] * dt - dis[:-1] * dt / B["eta_d"]
    assert np.max(np.abs(e_next - e_pred)) < 1e-9, "storage energy integration violated"
    assert soc.min() >= B["reserve_soc"] * 100 - 1e-6 and soc.max() <= 100 + 1e-6
    volts = voltages(tl, rng, 230.0, [0.9, 0.7, 0.7], net_ph)
    return dict(pv=pv, load=load, load_ph=load_ph, batch=batch, batch_runs=batch_runs, ch=ch, dis=dis, e=e_arr,
                soc=soc, v_term=v_term, i_dc=i_dc_native, p_dc=p_dc_native, t_bat=t_bat, i_lim_dis=i_lim_dis,
                net_ph=net_ph, net=net, imp=imp, exp=exp_, volts=volts, cap_kwh=cap)


def counters_wh(power_kw, base_wh):
    """Counter value at minute i = energy accumulated strictly before minute i (exact integer Wh)."""
    cum = np.concatenate([[0.0], np.cumsum(power_kw / 60.0)])[: len(power_kw)]
    return np.array([base_wh + int(round(x * 1000.0)) for x in cum], dtype=object)


