def latent(seed, start, days):
    tl = gd.Timeline(start, days)
    rng = np.random.default_rng(seed)
    wx = gd.make_weather(tl, rng)
    specs = []
    for prov in ("huawei", "fronius", "solaredge"):
        specs += [s for s in gd.SITE_SPECS if s["provider"] == prov][:3]
    sims = {s["key"]: gd.simulate_site(s, tl, wx, np.random.default_rng([seed, idx + 1]))
            for idx, s in enumerate(specs)}
    return tl, wx, specs, sims


def plane_poa(wx, tilt_deg, az_deg, lag_min=0):
    """Plane-of-array irradiance with generate_demo's own clear-sky/cloud model (no shading)."""
    c = np.roll(wx["cloud"], lag_min)
    zen, az_sun = wx["zen"], wx["az"]
    cosz = np.cos(zen)
    ghi_cs = np.where(cosz > 0, 1098 * cosz * np.exp(-0.057 / np.maximum(cosz, 0.01)), 0.0)
    dhi_cs = 0.13 * ghi_cs
    dni_cs = np.where(cosz > 0.03, (ghi_cs - dhi_cs) / np.maximum(cosz, 0.03), 0.0).clip(0, 1000)
    dni = dni_cs * (1 - c) ** 1.4
    dhi = dhi_cs + 0.5 * c * (1 - 0.5 * c) * (ghi_cs - dhi_cs)
    ghi = dni * np.maximum(cosz, 0) + dhi
    tilt, aza = math.radians(tilt_deg), math.radians(az_deg)
    cos_aoi = cosz * math.cos(tilt) + np.sin(zen) * math.sin(tilt) * np.cos(np.radians(az_sun) - aza)
    poa = dni * np.maximum(cos_aoi, 0) + dhi * (1 + math.cos(tilt)) / 2 + 0.2 * ghi * (1 - math.cos(tilt)) / 2
    return np.where(cosz > 0, poa, 0.0), c


def phase_weights(rng, n, base):
    """Slowly varying per-phase load split (sums to 1)."""
    w = np.array([b * (1 + 0.25 * gd.ar1(rng, n, 0.995)) for b in base])
    w = np.clip(w, 0.05, None)
    return w / w.sum(axis=0)


def voltages(tl, rng, v_base, z, net_phases):
    h = tl.local_hour
    diurnal = -2.5 * gd.gauss(h, 20.0, 1.5) + 0.8 * gd.gauss(h, 3.0, 2.0)
    out = []
    for k, zk in enumerate(z):
        nk = net_phases[k]
        out.append(v_base + diurnal + zk * (np.maximum(-nk, 0) - 0.25 * np.maximum(nk, 0)) + 0.4 * gd.ar1(rng, tl.n, 0.9))
    return out


