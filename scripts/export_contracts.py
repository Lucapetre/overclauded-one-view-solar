"""Generate OpenAPI and TypeScript directly from the running application's schemas."""

import argparse
import json
from pathlib import Path

from backend.main import create_app
from backend.models import SiteRegistration, TelemetryRecord


def typescript(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "enum" in schema:
        return " | ".join(json.dumps(item) for item in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"])
    for union in ("anyOf", "oneOf"):
        if union in schema:
            return " | ".join(typescript(item) for item in schema[union])
    if "allOf" in schema:
        return " & ".join(typescript(item) for item in schema["allOf"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{typescript(schema['items'])}>"
    if kind == "object" or "properties" in schema:
        required = set(schema.get("required", []))
        fields = [
            f"{json.dumps(key)}{'' if key in required else '?'}: {typescript(value)};"
            for key, value in schema.get("properties", {}).items()
        ]
        additional = schema.get("additionalProperties")
        if isinstance(additional, dict):
            fields.append(f"[key: string]: {typescript(additional)};")
        elif additional is True:
            fields.append("[key: string]: unknown;")
        return "{ " + " ".join(fields) + " }"
    return {
        "string": "string",
        "number": "number",
        "integer": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


def artifacts() -> dict[str, str]:
    schema = create_app().openapi()
    lines = [
        "// Generated by scripts/export_contracts.py; do not edit.",
        "// ISO 8601 timestamps are strings. All API numeric units are explicit.",
        "",
    ]
    for name, definition in sorted(schema["components"]["schemas"].items()):
        lines.append(f"export type {name} = {typescript(definition)};")
    lines += ["", "export type ApiRoutes = {"]
    for path, methods in schema["paths"].items():
        lines.append(f"  {json.dumps(path)}: {{")
        for method, operation in methods.items():
            if method not in ("get", "post", "put", "patch", "delete"):
                continue
            success = next(
                response
                for code, response in operation["responses"].items()
                if code.startswith("2")
            )
            response_type = (
                typescript(
                    success.get("content", {})
                    .get("application/json", {})
                    .get("schema", {})
                )
                if "content" in success
                else "void"
            )
            body = (
                operation.get("requestBody", {})
                .get("content", {})
                .get("application/json", {})
                .get("schema")
            )
            query = {"type": "object", "properties": {}, "required": []}
            params = {"type": "object", "properties": {}, "required": []}
            for parameter in operation.get("parameters", []):
                target = (
                    query
                    if parameter["in"] == "query"
                    else params
                    if parameter["in"] == "path"
                    else None
                )
                if target is not None:
                    target["properties"][parameter["name"]] = parameter["schema"]
                    if parameter.get("required"):
                        target["required"].append(parameter["name"])
            lines.append(
                f"    {method}: {{ response: {response_type}; body: {typescript(body) if body else 'never'}; query: {typescript(query)}; params: {typescript(params)} }};"
            )
        lines.append("  };")
    lines.append("};\n")
    return {
        "openapi.json": json.dumps(schema, indent=2, sort_keys=True) + "\n",
        "index.ts": "\n".join(lines),
        "telemetry.schema.json": json.dumps(
            TelemetryRecord.model_json_schema(), indent=2, sort_keys=True
        )
        + "\n",
        "site-registration.schema.json": json.dumps(
            SiteRegistration.model_json_schema(), indent=2, sort_keys=True
        )
        + "\n",
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    destination = Path(__file__).resolve().parents[1] / "packages" / "contracts"
    destination.mkdir(parents=True, exist_ok=True)
    for filename, content in artifacts().items():
        path = destination / filename
        if arguments.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(
                    f"Outdated contract: {path}. Run scripts/export_contracts.py"
                )
        else:
            path.write_text(content)


if __name__ == "__main__":
    main()
