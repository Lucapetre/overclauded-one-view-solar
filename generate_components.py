class Ctx:
    def __init__(self, tl, seed):
        self.tl, self.seed = tl, seed
        self.faults = []
        self.golden = {}

    def rng(self, k):
        return np.random.default_rng([self.seed, 4242, k])

    def local(self, y, m, d, hh, mm=0, ss=0):
        return datetime(y, m, d, hh, mm, ss, tzinfo=TZ).astimezone(UTC)

    def idx(self, dt_utc):
        return int(round((dt_utc - self.tl.start_utc).total_seconds() / 60))

    def fault(self, **kw):
        self.faults.append(kw)


def snapshot_times(ctx, step_min, rng, jitter=(0.2, 1.4), upload=(2.0, 25.0)):
    for i in range(0, ctx.tl.n, step_min):
        rec = ctx.tl.utc(i) + timedelta(seconds=float(rng.uniform(*jitter)))
        recv = rec + timedelta(seconds=float(rng.uniform(*upload)))
        yield i, rec, recv


def m1_blocks(f1, i, imp_wh, exp_wh, swap=False):
    fw = (lambda x: list(reversed(f32_words(x)))) if swap else f32_words
    iw = (lambda x: list(reversed(i64_words(x)))) if swap else i64_words
    p = [f1["net_ph"][k][i] for k in range(3)]
    v = [f1["volts"][k][i] for k in range(3)]
    cur = [abs(p[k]) * 1000.0 / (v[k] * 0.97) for k in range(3)]
    tot = sum(p)
    return [
        {"start_address": 2999, "words": fw(cur[0]) + fw(cur[1]) + fw(cur[2])},
        {"start_address": 3027, "words": fw(v[0]) + fw(v[1]) + fw(v[2])},
        {"start_address": 3053, "words": fw(p[0]) + fw(p[1]) + fw(p[2]) + fw(tot)},
        {"start_address": 3109, "words": fw(f1["freq"][i])},
        {"start_address": 3203, "words": iw(imp_wh) + iw(exp_wh)},
        {"start_address": 44999, "words": [0]},
    ], dict(p=p, v=v, cur=cur, tot=tot)


