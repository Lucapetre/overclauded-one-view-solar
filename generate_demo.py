def fronius_powerflow(spec, sim, i, ts):
    variant = spec["profile_variant"]
    inv_w = sim["inv_ac"][i] * 1000.0
    producing = sim["pv_used"][i] > 0.012
    site = {"E_Day": None, "E_Total": r(sim["lifetime_kwh"][i] * 1000, 1), "E_Year": None,
            "Meter_Location": "unknown", "Mode": "produce-only",
            "P_Akku": None, "P_Grid": None, "P_Load": None, "P_PV": None,
            "rel_Autonomy": None, "rel_SelfConsumption": None}
    inverters = {}
    if variant == "snapinverter":
        site["E_Day"] = r(sim["daily_kwh"][i] * 1000, 1)
        site["E_Year"] = r(sim["year_kwh"][i] * 1000, 1)
        site["P_PV"] = r(inv_w, 1) if producing else None  # SnapInverter: AC output; null while asleep
        if producing:
            inverters["1"] = {"DT": 123, "E_Day": site["E_Day"], "E_Total": site["E_Total"],
                              "E_Year": site["E_Year"], "P": r(inv_w, 1)}
    else:  # gen24_hybrid: P_PV is DC generation; E_Day/E_Year null on this model family
        site["Mode"] = "bidirectional"
        site["P_PV"] = r(sim["pv_used"][i] * 1000, 1)
        site["P_Akku"] = r((sim["dis"][i] - sim["ch"][i]) * 1000, 1)  # negative = charging
        soc = sim["soc"][i]
        mode = "battery full" if soc >= 99.5 else ("nearly depleted" if soc <= spec["battery"]["reserve"] * 100 + 0.5
                                                    else "normal")
        inverters["1"] = {"Battery_Mode": mode, "DT": 1, "E_Day": None, "E_Total": site["E_Total"],
                          "E_Year": None, "P": r(inv_w, 1), "SOC": r(soc, 1)}
    if spec["meter"]:
        site["Meter_Location"] = "grid"
        if variant == "snapinverter":
            site["Mode"] = "meter"
        site["P_Grid"] = r((sim["imp"][i] - sim["exp"][i]) * 1000, 1)
        site["P_Load"] = r(-sim["load"][i] * 1000, 1)
        ld, ia = sim["load"][i], sim["inv_ac"][i]
        site["rel_Autonomy"] = r(100 * (1 - sim["imp"][i] / ld), 1) if ld > 0 else None
        site["rel_SelfConsumption"] = r(100 * (1 - sim["exp"][i] / ia), 1) if ia > 0.01 else None
    return {"Body": {"Data": {"Inverters": inverters, "Site": site, "Version": "12"}},
            "Head": fronius_head(ts)}


def fronius_cid(spec, sim, i, ts):
    args = {"DataCollection": "CommonInverterData", "DeviceClass": "Inverter", "DeviceId": "1", "Scope": "Device"}
    variant = spec["profile_variant"]
    producing = sim["pv_used"][i] > 0.012 or (spec["battery"] is not None)
    if variant == "snapinverter" and not producing:
        # Documented-style unavailable state while a SnapInverter sleeps at night
        return {"Body": {"Data": {}}, "Head": fronius_head(ts, args, code=12,
                                                           reason="synthetic: device not available")}
    phases = spec["inverter"]["phases"]
    pac = sim["inv_ac"][i] * 1000.0
    uac = sim["volts"][0][i]
    udc = float(np.mean([s[1][i] for s in sim["strings"]]))
    idc = (sim["pv_used"][i] * 1000.0 / udc) if udc > 1 else 0.0
    data = {
        "DAY_ENERGY": {"Unit": "Wh", "Value": r(sim["daily_kwh"][i] * 1000, 1) if variant == "snapinverter" else None},
        "DeviceStatus": {"ErrorCode": 0, "LEDColor": 2, "LEDState": 0, "MgmtTimerRemainingTime": -1,
                         "StateToReset": False, "StatusCode": 7},
        "FAC": {"Unit": "Hz", "Value": r(sim["freq"][i], 2)},
        "IAC": {"Unit": "A", "Value": r(pac / (uac * phases) if uac > 1 else 0.0, 2)},
        "IDC": {"Unit": "A", "Value": r(idc, 2)},
        "PAC": {"Unit": "W", "Value": r(pac, 1)},
        "TOTAL_ENERGY": {"Unit": "Wh", "Value": r(sim["lifetime_kwh"][i] * 1000, 1)},
        "UAC": {"Unit": "V", "Value": r(uac, 1)},
        "UDC": {"Unit": "V", "Value": r(udc, 1)},
        "YEAR_ENERGY": {"Unit": "Wh", "Value": r(sim["year_kwh"][i] * 1000, 1) if variant == "snapinverter" else None},
    }
    return {"Body": {"Data": data}, "Head": fronius_head(ts, args)}


