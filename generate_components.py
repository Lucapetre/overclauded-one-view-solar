def lag1(x, k):
    """First-order lag with time constant k samples (deterministic)."""
    y = np.empty_like(x)
    y[0] = x[0]
    for i in range(1, len(x)):
        y[i] = y[i - 1] + (x[i] - y[i - 1]) / k
    return y


def envelope(delivery_id, profile_id, endpoint_key, asset_id, collector_id, gateway_id, scope, recorded, received,
             http_status=None, ok=True, error=None):
    e = {"transport_schema": SCHEMA, "synthetic": True, "delivery_id": delivery_id,
         "provider_profile_id": profile_id, "endpoint_key": endpoint_key, "binding": {"asset_id": asset_id},
         "collector_id": collector_id, "gateway_id": gateway_id, "request_scope": scope,
         "recorded_at_utc": iso_z(recorded), "received_at_utc": iso_z(received),
         "transport_status": "ok" if ok else "failed", "http_status": http_status, "transport_error": error}
    return e


class Stream:
    """One output file of deliveries; sorted by (received, seq) when written (arrival order)."""

    def __init__(self, path, profile_id, endpoint_key, family, asset_ids, dataset="delivery", role="production"):
        self.path, self.profile_id, self.endpoint_key = path, profile_id, endpoint_key
        self.family, self.asset_ids, self.dataset, self.role = family, asset_ids, dataset, role
        self.items = []

    def add(self, env, payload=None, received=None, seq=None):
        obj = {ENV: env}
        if payload is not None:
            obj["payload"] = payload
        self.items.append((received or env["received_at_utc"], seq if seq is not None else len(self.items), obj))

    def write(self, root: Path):
        p = root / self.path
        p.parent.mkdir(parents=True, exist_ok=True)
        items = sorted(self.items, key=lambda x: (x[0], x[1]))
        text = "".join(dumps(obj) + "\n" for _, _, obj in items).encode("utf-8")
        if self.path.endswith(".gz"):  # deterministic gzip: no embedded file name, mtime 0
            with open(p, "wb") as raw, gzip.GzipFile(filename="", mode="wb", fileobj=raw, mtime=0,
                                                     compresslevel=9) as gz:
                gz.write(text)
        else:
            p.write_bytes(text)
        return {"path": self.path, "dataset": self.dataset, "family": self.family, "profile_id": self.profile_id,
                "endpoint_key": self.endpoint_key, "asset_ids": self.asset_ids, "format": "ndjson_envelope",
                "role": self.role, "lines": len(items), "sha256": sha256_file(p)}


