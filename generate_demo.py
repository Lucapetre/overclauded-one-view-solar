def dumps(obj) -> str:
    return json.dumps(obj, separators=(",", ":"), ensure_ascii=False)


def iso_z(dt: datetime) -> str:
    return dt.astimezone(UTC).isoformat(timespec="milliseconds").replace("+00:00", "Z")


def iso_local(dt: datetime) -> str:
    return dt.astimezone(TZ).isoformat(timespec="seconds")


def naive_local(dt: datetime) -> str:
    return dt.astimezone(TZ).strftime("%Y-%m-%d %H:%M:%S")


def epoch_ms(dt: datetime) -> int:
    return int(round(dt.timestamp() * 1000))


def r(x, n):
    if x is None:
        return None
    return round(float(x), n)


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def ar1(rng, n, phi, sigma=1.0):
    eps = rng.normal(0.0, sigma * math.sqrt(1 - phi * phi), n)
    x = np.empty(n)
    x[0] = rng.normal(0.0, sigma)
    for i in range(1, n):
        x[i] = phi * x[i - 1] + eps[i]
    return x


def gauss(h, mu, sd):
    return np.exp(-0.5 * ((h - mu) / sd) ** 2)


class Timeline:
    """One-minute latent timeline from local midnight of `start` for `days` local days."""

    def __init__(self, start: date, days: int):
        self.start_date = start
        self.days = days
        self.start_local = datetime.combine(start, time(0), tzinfo=TZ)
        self.end_local = datetime.combine(start + timedelta(days=days), time(0), tzinfo=TZ)
        self.start_utc = self.start_local.astimezone(UTC)
        self.end_utc = self.end_local.astimezone(UTC)
        self.n = int((self.end_utc - self.start_utc).total_seconds() // 60)
        self.epoch = self.start_utc.timestamp() + 60.0 * np.arange(self.n)
        local = [(self.start_utc + timedelta(minutes=i)).astimezone(TZ) for i in range(self.n)]
        self.local_hour = np.array([lt.hour + lt.minute / 60.0 for lt in local])
        self.dates = [start + timedelta(days=k) for k in range(days)]
        index_of = {d: k for k, d in enumerate(self.dates)}
        self.day_idx = np.array([index_of[lt.date()] for lt in local])
        self.day_start = [int(np.argmax(self.day_idx == k)) for k in range(days)]
        self.weekday = [d.weekday() for d in self.dates]

    def utc(self, i) -> datetime:
        return self.start_utc + timedelta(minutes=int(i))

    def index_of_local(self, day: int, hour: float) -> int:
        dt = datetime.combine(self.dates[day], time(0), tzinfo=TZ) + timedelta(hours=hour)
        return int(round((dt.astimezone(UTC) - self.start_utc).total_seconds() / 60))


