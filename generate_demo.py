def solar_position(epoch_s, lat_deg, lon_deg):
    d64 = epoch_s.astype("int64").astype("datetime64[s]")
    doy = (d64.astype("datetime64[D]") - d64.astype("datetime64[Y]")).astype(int) + 1
    hour = (epoch_s % 86400) / 3600.0
    g = 2 * np.pi / 365.0 * (doy - 1 + (hour - 12) / 24.0)
    eqt = 229.18 * (0.000075 + 0.001868 * np.cos(g) - 0.032077 * np.sin(g)
                    - 0.014615 * np.cos(2 * g) - 0.040849 * np.sin(2 * g))
    decl = (0.006918 - 0.399912 * np.cos(g) + 0.070257 * np.sin(g) - 0.006758 * np.cos(2 * g)
            + 0.000907 * np.sin(2 * g) - 0.002697 * np.cos(3 * g) + 0.00148 * np.sin(3 * g))
    tst = hour * 60 + eqt + 4 * lon_deg
    ha = np.radians(tst / 4.0 - 180.0)
    lat = np.radians(lat_deg)
    cosz = np.sin(lat) * np.sin(decl) + np.cos(lat) * np.cos(decl) * np.cos(ha)
    cosz = np.clip(cosz, -1, 1)
    zen = np.arccos(cosz)
    az = np.degrees(np.arctan2(np.sin(ha), np.cos(ha) * np.sin(lat) - np.tan(decl) * np.cos(lat))) + 180.0
    return zen, az


def make_weather(tl: Timeline, rng):
    n = tl.n
    slow = ar1(rng, n, 0.97)
    fast = ar1(rng, n, 0.80)
    c = np.zeros(n)
    tamb = np.zeros(n)
    plans = [DAY_PLAN[k % len(DAY_PLAN)] for k in range(tl.days)]
    h = tl.local_hour
    for k, plan in enumerate(plans):
        m = tl.day_idx == k
        cd = plan["c_mean"] + plan["c_var"] * (0.7 * slow[m] + 0.3 * fast[m])
        if "cumulus" in plan:
            a, b = plan["cumulus"]
            win = (h[m] >= a) & (h[m] <= b)
            cd = cd + win * 0.45 * np.clip(slow[m] + 0.3, 0, None)
        if "morning_clouds" in plan:
            cd = cd + (h[m] < plan["morning_clouds"]) * 0.55
        c[m] = cd
        tmin, tmax = plan["tmin"], plan["tmax"]
        prev_tmax = plans[k - 1]["tmax"] if k > 0 else tmax - 2
        next_tmin = plans[k + 1]["tmin"] if k + 1 < len(plans) else tmin
        hh = h[m]
        t = np.where(
            (hh >= 5.5) & (hh <= 15.5),
            tmin + (tmax - tmin) * (1 - np.cos(np.pi * (hh - 5.5) / 10.0)) / 2,
            np.where(hh > 15.5,
                     next_tmin + (tmax - next_tmin) * (1 + np.cos(np.pi * (hh - 15.5) / 14.0)) / 2,
                     tmin + (prev_tmax - tmin) * (1 + np.cos(np.pi * (hh + 24 - 15.5) / 14.0)) / 2))
        tamb[m] = t
    c = np.clip(c, 0.0, 1.0)
    tamb = tamb + 0.4 * ar1(rng, n, 0.99)
    freq = 50.0 + np.clip(0.012 * ar1(rng, n, 0.98), -0.06, 0.06)
    zen, az = solar_position(tl.epoch, LOCATION["latitude_deg"], LOCATION["longitude_deg"])
    return dict(cloud=c, tamb=tamb, freq=freq, zen=zen, az=az, plans=[p["label"] for p in plans])


def make_load(spec, tl: Timeline, tamb, rng):
    n, h = tl.n, tl.local_hour
    L = spec["load"]
    base = L["base"] * (1 + 0.15 * ar1(rng, n, 0.995))
    load = base + L["morning"] * gauss(h, 7.2, 0.55) + L["evening"] * gauss(h, 20.2, 1.2) \
        + 0.35 * L["morning"] * gauss(h, 13.0, 0.8)
    load = load * (1 + 0.08 * ar1(rng, n, 0.9))
    sc = L["appliances"]

    def block(start, dur, kw):
        a, b = max(0, start), min(n, start + dur)
        if a < b:
            load[a:b] += kw

    for day in range(tl.days):
        d0 = tl.day_start[day]
        if rng.random() < 0.55:  # washing machine: heating phase then motor phase
            s = d0 + int(rng.uniform(9, 16) * 60)
            block(s, 20, 2.0 * sc)
            block(s + 20, int(rng.uniform(40, 70)), 0.3 * sc)
        if rng.random() < 0.7:  # dishwasher
            block(d0 + int(rng.uniform(20, 22) * 60), 45, 1.8 * sc)
        if rng.random() < 0.5:  # oven
            block(d0 + int(rng.uniform(18, 19.5) * 60), 40, 2.3 * sc)
        block(d0 + int(rng.uniform(6.8, 8.0) * 60), 4, 2.0)  # kettle
        ev = L.get("ev")
        if ev and day in ev["days"]:
            block(tl.index_of_local(day, ev["start_h"]), int(ev["kwh"] / ev["kw"] * 60), ev["kw"])
    if L.get("ac_kw", 0) > 0:
        duty = (np.arange(n) % 20) < 14  # compressor cycling
        on = (tamb > 29.0) & (h > 11) & (h < 21) & duty
        load = load + on * L["ac_kw"]
    return np.clip(load, 0.05, None)


def eta_curve(p_dc, rated):
    lf = np.clip(p_dc / rated, 0, None)
    return 0.972 - 0.035 * np.exp(-lf * 10)


def simulate_site(spec, tl: Timeline, wx, rng):
    n = tl.n
    lag = spec["cloud_lag_min"]
    c = np.roll(wx["cloud"], lag)
    zen, az_sun = wx["zen"], wx["az"]
    cosz = np.cos(zen)
    elev = 90 - np.degrees(zen)
    ghi_cs = np.where(cosz > 0, 1098 * cosz * np.exp(-0.057 / np.maximum(cosz, 0.01)), 0.0)
    dhi_cs = 0.13 * ghi_cs
    dni_cs = np.where(cosz > 0.03, (ghi_cs - dhi_cs) / np.maximum(cosz, 0.03), 0.0).clip(0, 1000)
    dni = dni_cs * (1 - c) ** 1.4
    dhi = dhi_cs + 0.5 * c * (1 - 0.5 * c) * (ghi_cs - dhi_cs)
    ghi = dni * np.maximum(cosz, 0) + dhi
    tamb = wx["tamb"]
    inv = spec["inverter"]
    rated = inv["rated_ac_kw"]

    shade = np.ones(n)
    sh = spec.get("shading")
    if sh:
        if sh["kind"] == "morning_tree":
            shade = np.where((az_sun < sh["az_max"]) & (elev < sh["elev_max"]), sh["beam_factor"], 1.0)
        else:
            shade = np.where((az_sun > sh["az_min"]) & (elev < sh["elev_max"]), sh["beam_factor"], 1.0)

    strings = []  # list of (p_dc, v, i, array_name)
    poa_mean = np.zeros(n)
    total_kwp = sum(a["kwp"] for a in spec["arrays"])
    for arr in spec["arrays"]:
        tilt, aza = math.radians(arr["tilt"]), math.radians(arr["az"])
        cos_aoi = cosz * math.cos(tilt) + np.sin(zen) * math.sin(tilt) * np.cos(np.radians(az_sun) - aza)
        beam = dni * np.maximum(cos_aoi, 0) * shade
        poa = beam + dhi * (1 + math.cos(tilt)) / 2 + 0.2 * ghi * (1 - math.cos(tilt)) / 2
        poa = np.where(cosz > 0, poa, 0.0)
        poa_mean += poa * arr["kwp"] / total_kwp
        tcell = tamb + poa * 25.0 / 800.0
        for s in range(arr["strings"]):
            kwp = arr["kwp"] / arr["strings"]
            p = kwp * poa / 1000.0 * (1 - 0.0037 * (tcell - 25)) * (1 - 0.08)
            modules = max(6, int(round(kwp / 0.41)))
            v = np.where(poa > 15, modules * 34.5 * (1 - 0.0035 * (tcell - 25)),
                         np.where(poa > 2, modules * 20.0 * poa / 15.0, 0.0))
            strings.append([np.clip(p, 0, None), v, arr["name"]])
    flt = spec.get("fault")
    if flt:
        start_i = tl.index_of_local(flt["from_day"], flt["from_h"]) if flt["from_day"] < tl.days else n
        strings[flt["string_index"]][0][start_i:] *= flt["factor"]
        strings[flt["string_index"]][1][start_i:] *= flt["factor"]
    for s in strings:
        s.append(np.where(s[1] > 1, s[0] * 1000.0 / np.maximum(s[1], 1), 0.0))  # current A
    pv_dc = sum(s[0] for s in strings)

    load = make_load(spec, tl, tamb, rng)
    bat = spec.get("battery")
    ch = np.zeros(n)
    dis = np.zeros(n)
    soc = np.full(n, np.nan)
    e_bat = np.full(n, np.nan)
    dt = 1 / 60.0
    if bat:
        eta = 0.965
        cap = bat["capacity_kwh"]
        e = cap * bat["soc0"]
        emin, emax = cap * bat["reserve"], cap
        inv_ac = np.zeros(n)
        for i in range(n):
            p = pv_dc[i] if pv_dc[i] > 0.012 else 0.0
            soc[i] = 100.0 * e / cap
            e_bat[i] = e
            if p * eta >= load[i]:
                surplus = p - load[i] / eta
                room = max((emax - e) / (bat["eta_c"] * dt), 0.0)
                c_ = max(min(surplus, bat["p_max_kw"], room), 0.0)
                if (p - c_) * eta > rated:  # absorb clipping if possible
                    c_ = max(c_, min(bat["p_max_kw"], room, p - rated / eta))
                ch[i] = c_
                inv_ac[i] = min((p - c_) * eta, rated)
            else:
                deficit = load[i] - p * eta
                avail = max((e - emin) * bat["eta_d"] / dt, 0.0)
                d_ = max(min(deficit / eta, bat["p_max_kw"], avail), 0.0)
                dis[i] = d_
                inv_ac[i] = min((p + d_) * eta, rated)
            e += ch[i] * bat["eta_c"] * dt - dis[i] / bat["eta_d"] * dt
        pv_used = np.where(pv_dc > 0.012, pv_dc, 0.0)
        losses = pv_used + dis - ch - inv_ac
    else:
        p = np.where(pv_dc > 0.012, pv_dc, 0.0)
        inv_ac = np.minimum(p * eta_curve(p, rated), rated)
        losses = p - inv_ac
    imp = np.maximum(load - inv_ac, 0.0)
    exp_ = np.maximum(inv_ac - load, 0.0)
    pv_used = np.where(pv_dc > 0.012, pv_dc, 0.0)
    balance = pv_used + imp + dis - (load + exp_ + ch + losses)
    assert np.max(np.abs(balance)) < 1e-9, "AC-boundary energy balance violated"

    # inverter temperature (first-order lag)
    lf = inv_ac / rated
    t_env = tamb + (np.maximum(0.0, tamb - 30.0) * 1.25 + 2.0 if inv["garage"] else 0.0)
    target = np.where(inv_ac > 0.01, t_env + inv["vent_offset"] + inv["k_load"] * lf, t_env + 1.0)
    inv_temp = np.empty(n)
    inv_temp[0] = target[0]
    for i in range(1, n):
        inv_temp[i] = inv_temp[i - 1] + (target[i] - inv_temp[i - 1]) / 12.0
    bat_temp = None
    if bat:
        tgt = 23 + 0.25 * (tamb - 23) + 3.0 * (ch + dis) / bat["p_max_kw"]
        bat_temp = np.empty(n)
        bat_temp[0] = tgt[0]
        for i in range(1, n):
            bat_temp[i] = bat_temp[i - 1] + (tgt[i] - bat_temp[i - 1]) / 20.0

    # phase voltages
    h = tl.local_hour
    g = spec["grid"]
    diurnal = -2.5 * gauss(h, 20.0, 1.5) + 0.8 * gauss(h, 3.0, 2.0)
    event = np.zeros(n)
    ev = g.get("event")
    if ev:
        for d in ev["days"]:
            if d < tl.days:
                a = tl.index_of_local(d, ev["start_h"])
                b = tl.index_of_local(d, ev["end_h"])
                ramp = np.clip(np.minimum(np.arange(n) - a, b - np.arange(n)) / 20.0, 0, 1)
                event += ev["dv"] * ramp
    volts = []
    for z in g["z"]:
        volts.append(g["v_base"] + diurnal + z * (exp_ - 0.25 * imp) + event + 0.5 * ar1(rng, n, 0.9))

    # counters: value at sample i = energy accumulated strictly before minute i
    cum = np.concatenate([[0.0], np.cumsum(inv_ac * dt)])[:n]
    day_cum0 = np.array([cum[tl.day_start[k]] for k in tl.day_idx])
    lifetime_kwh = spec["lifetime_kwh"] + cum
    daily_kwh = cum - day_cum0
    year_offset_kwh = 2650.0 + 37.0 * (sum(map(ord, spec["key"])) % 10)  # synthetic E_Year baseline
    out = dict(pv_dc=pv_dc, pv_used=pv_used, strings=strings, poa=poa_mean, ghi=ghi, inv_ac=inv_ac, load=load,
               imp=imp, exp=exp_, ch=ch, dis=dis, soc=soc, e_bat=e_bat, losses=losses, inv_temp=inv_temp,
               bat_temp=bat_temp, volts=volts, freq=wx["freq"], tamb=tamb, cloud=c,
               lifetime_kwh=lifetime_kwh, daily_kwh=daily_kwh, year_kwh=year_offset_kwh + cum)
    if bat:
        ccum = np.concatenate([[0.0], np.cumsum(ch * dt)])[:n]
        dcum = np.concatenate([[0.0], np.cumsum(dis * dt)])[:n]
        out["bat_ch_life_kwh"] = 1234.567 + ccum
        out["bat_dis_life_kwh"] = 1100.321 + dcum
        out["bat_ch_day_kwh"] = ccum - np.array([ccum[tl.day_start[k]] for k in tl.day_idx])
        out["bat_dis_day_kwh"] = dcum - np.array([dcum[tl.day_start[k]] for k in tl.day_idx])
    return out


